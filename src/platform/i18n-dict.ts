/** 词典 key 全集：动态拼接 key 必须先经此类映射表，禁止模板直拼 tr()。 */
export type I18nKey = keyof typeof D;

/** 展示语言 → Intl locale（数字/日期展示本地化用；存储键与 CSV 不跟语言，见 queries.ts）。 */
export const LANG_LOCALE: Record<Lang, string> = {
  '0': 'zh-CN',
  '1': 'zh-TW',
  '2': 'en-US',
};

/** tr 插值变量：`{k: key}` 表示嵌套翻译该词条（用于 what 这类标签位）。 */
export type TrVar = string | number | { k: I18nKey };
export type TrVars = Record<string, TrVar>;

export function tr(lang: Lang, key: I18nKey, vars?: TrVars): string {
  const t = D[key];
  if (!t) return key;
  let s: string = t[Number(lang)] ?? t[0];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const rep = typeof v === 'object' ? tr(lang, v.k) : String(v);
      s = s.split(`{${k}}`).join(rep);
    }
  }
  return s;
}
