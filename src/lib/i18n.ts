export function tr(lang: Lang, key: string): string {
  const t = D[key];
  if (!t) return key;
  return t[Number(lang)] ?? t[0];
}

/** 以当前配置语言取词（组件内用 tr($options.lang, key) 以保持响应式） */
export function tt(key: string): string {
  return tr(snapshotOptions().lang, key);
}
